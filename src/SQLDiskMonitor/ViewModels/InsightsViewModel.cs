using System.Collections.ObjectModel;
using System.IO;
using System.Net;
using System.Text;
using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using SQLDiskMonitor.Data;
using SQLDiskMonitor.Models;
using SQLDiskMonitor.Services;

namespace SQLDiskMonitor.ViewModels;

public partial class InsightsViewModel(MainViewModel shell) : PageViewModel(shell)
{
    public override string Title => "Bottlenecks";
    public override string Glyph => "";
    public override string Subtitle => "Ranked findings and recommendations for the selected period";

    public ObservableCollection<Finding> Findings { get; } = [];
    public ObservableCollection<Store.WaitStat> Waits { get; } = [];

    [ObservableProperty] private int _critical;
    [ObservableProperty] private int _high;
    [ObservableProperty] private int _medium;
    [ObservableProperty] private int _other;

    private AnalysisResult? _last;

    public override async Task RefreshAsync()
    {
        if (Server == null) return;
        var server = Server;
        var gen = ++Generation;
        IsBusy = true;
        var a = await Task.Run(() => Analytics.Analyse(Store, server.Id, Shell.RangeFrom, Shell.RangeTo, Cfg));
        IsBusy = false;
        if (server != Server || gen != Generation) return;
        _last = a;

        Findings.Clear();
        foreach (var f in a.Findings) Findings.Add(f);
        Waits.Clear();
        foreach (var w in a.Waits) Waits.Add(w);
        Critical = a.Findings.Count(f => f.Severity == Severity.Critical);
        High = a.Findings.Count(f => f.Severity == Severity.High);
        Medium = a.Findings.Count(f => f.Severity == Severity.Medium);
        Other = a.Findings.Count(f => f.Severity <= Severity.Low);
    }

    [RelayCommand]
    private void ExportReport()
    {
        if (_last == null || Server == null) return;
        var dlg = new Microsoft.Win32.SaveFileDialog
        {
            Filter = "HTML report (*.html)|*.html",
            FileName = $"{MetricsViewModel.Sanitise(Server.Name)}_storage_report_{DateTime.Now:yyyyMMdd}.html"
        };
        if (dlg.ShowDialog() != true) return;
        File.WriteAllText(dlg.FileName, BuildReport(_last, Server, Store.GetFiles(Server.Id)));
        MainViewModel.OpenUrl(dlg.FileName);
    }

    private string BuildReport(AnalysisResult a, ServerConnection s, List<DbFile> files)
    {
        static string E(string x) => WebUtility.HtmlEncode(x);
        var cur = Cfg.CurrencySymbol;
        var sb = new StringBuilder();
        sb.Append($$"""
            <!doctype html><html><head><meta charset="utf-8"><title>Storage report — {{E(s.Name)}}</title>
            <style>
            body{font-family:Segoe UI,system-ui,sans-serif;margin:32px auto;max-width:1100px;color:#1f2328;padding:0 16px}
            h1{font-weight:600;margin-bottom:4px} h2{margin-top:36px;font-weight:600;border-bottom:1px solid #d8dee4;padding-bottom:6px}
            .muted{color:#57606a} table{border-collapse:collapse;width:100%;font-size:13px} th,td{text-align:left;padding:6px 8px;border-bottom:1px solid #eaeef2}
            th{color:#57606a;font-weight:600} td.n{text-align:right;font-variant-numeric:tabular-nums}
            .f{border-left:4px solid #8c959f;padding:10px 14px;margin:10px 0;background:#f6f8fa;border-radius:4px}
            .Critical{border-color:#cf222e}.High{border-color:#bc4c00}.Medium{border-color:#9a6700}.Low{border-color:#0969da}
            .sev{font-size:11px;font-weight:700;letter-spacing:.04em;color:#57606a}
            </style></head><body>
            <h1>Storage report — {{E(s.Name)}}</h1>
            <div class="muted">{{E(s.HostName)}} · {{E(s.Version)}}<br>Period {{Shell.RangeFrom:yyyy-MM-dd HH:mm}} – {{Shell.RangeTo:yyyy-MM-dd HH:mm}} · generated by SQL Disk Monitor {{Shell.VersionText}}</div>
            <h2>Disks</h2><table><tr><th>Volume</th><th>Label</th><th>Drive / disk name</th><th>LUN</th><th>Tier</th><th class="n">Max IOPS</th><th class="n">Max MB/s</th>
            <th class="n">p95 IOPS</th><th class="n">p95 MB/s</th><th class="n">Read ms</th><th class="n">Write ms</th><th class="n">p95 pressure</th><th class="n">Free</th>
            """);
        if (Cfg.CostsEnabled) sb.Append("<th class=\"n\">Monthly</th>");
        sb.Append("</tr>");
        foreach (var d in a.Disks)
        {
            var c = d.Config;
            sb.Append($"<tr><td>{E(d.Volume)}</td><td>{E(c?.Label ?? "")}</td><td>{E(c?.NamesText ?? "")}</td><td>{c?.Lun}</td><td>{E(c?.Tier ?? "")}</td><td class=n>{c?.MaxIops:N0}</td><td class=n>{c?.MaxMbps:N0}</td>" +
                      $"<td class=n>{d.P95Iops:N0}</td><td class=n>{d.P95Mbps:N1}</td><td class=n>{d.AvgReadLatency:N1}</td><td class=n>{d.AvgWriteLatency:N1}</td>" +
                      $"<td class=n>{d.P95Pressure:N0} ({Pressure.Band(d.P95Pressure)})</td><td class=n>{d.FreePct:N0}%</td>");
            if (Cfg.CostsEnabled) sb.Append($"<td class=n>{cur}{c?.MonthlyCost:N2}</td>");
            sb.Append("</tr>");
            if (!string.IsNullOrWhiteSpace(c?.Notes)) sb.Append($"<tr><td></td><td colspan=12 class=muted>{E(c.Notes)}</td></tr>");
        }
        sb.Append("</table><h2>Findings</h2>");
        if (a.Findings.Count == 0) sb.Append("<p>No issues found in this period.</p>");
        foreach (var f in a.Findings)
            sb.Append($"<div class=\"f {f.Severity}\"><div class=sev>{f.SeverityText} · {E(f.Category)}</div><b>{E(f.Title)}</b><div>{E(f.Detail)}</div><div class=muted>{E(f.Recommendation)}</div></div>");

        sb.Append("<h2>IO waits</h2><table><tr><th>Wait</th><th class=n>Avg wait ms/s</th><th class=n>Avg ms per wait</th><th class=n>Peak ms/s</th></tr>");
        foreach (var w in a.Waits)
            sb.Append($"<tr><td>{w.WaitType}</td><td class=n>{w.AvgWaitMsPerSec:N1}</td><td class=n>{w.AvgMsPerWait:N2}</td><td class=n>{w.PeakWaitMsPerSec:N0}</td></tr>");

        sb.Append("</table><h2>Database files</h2><table><tr><th>Database</th><th>File</th><th>Type</th><th>Volume</th><th class=n>Size GB</th><th>Growth</th><th class=n>Avg IOPS</th><th class=n>Read ms</th><th class=n>Write ms</th><th>Path</th></tr>");
        var stats = a.FileStats.ToDictionary(x => (x.DatabaseId, x.FileId));
        foreach (var f in files.OrderBy(f => f.Volume).ThenBy(f => f.DatabaseName))
        {
            stats.TryGetValue((f.DatabaseId, f.FileId), out var st);
            sb.Append($"<tr><td>{E(f.DatabaseName)}</td><td>{E(f.LogicalName)}</td><td>{f.TypeDesc}</td><td>{E(f.Volume)}</td><td class=n>{f.SizeMb / 1024:N1}</td><td>{f.GrowthDisplay}</td>" +
                      $"<td class=n>{(st == null ? 0 : st.ReadIops + st.WriteIops):N1}</td><td class=n>{st?.ReadLatency:N1}</td><td class=n>{st?.WriteLatency:N1}</td><td class=muted>{E(f.PhysicalName)}</td></tr>");
        }
        sb.Append("</table></body></html>");
        return sb.ToString();
    }
}
